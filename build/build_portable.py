#!/usr/bin/env python3
"""Build portable/knowledge/ and portable/ai-filmmaker-full.md from the skill folder.

The skill (skills/ai-filmmaker/) is the single source of truth. This script merges its
files into at most 10 knowledge files (the Custom GPT / Gemini Gem upload cap) and one
all-in-one file for pasting into any LLM.

  python3 build/build_portable.py           # write the files
  python3 build/build_portable.py --check   # exit 1 if the committed files are stale
"""

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "ai-filmmaker"
REF = SKILL / "references"
OUT = ROOT / "portable"
KNOWLEDGE = OUT / "knowledge"
SYSTEM_PROMPT = OUT / "SYSTEM_PROMPT.md"
SYSTEM_PROMPT_LIMIT = 7500  # Custom GPT instructions cap is 8,000 characters

# knowledge file -> (title, [source files relative to the skill folder])
GROUPS = [
    ("00-director-logic.md", "Director logic (the skill's SKILL.md)", ["SKILL.md"]),
    ("01-principles-and-quality-gate.md", "Principles, quality gate, mechanism not mood",
     ["references/principles.md", "references/translation/mechanism-not-mood.md"]),
    ("02-workflow-and-playbooks.md", "The 7-stage workflow and the three playbooks",
     ["references/workflow/seven-stages.md", "references/workflow/playbook-cinematic.md",
      "references/workflow/playbook-ugc-persona.md", "references/workflow/playbook-product-commercial.md"]),
    ("03-craft-story-performance-shots.md", "Craft: story, performance, shot design",
     ["references/craft/story-structure.md", "references/craft/directing-performance.md",
      "references/craft/shot-design-and-coverage.md"]),
    ("04-craft-camera-light-colour.md", "Craft: cinematography, lighting, colour",
     ["references/craft/cinematography.md", "references/craft/lighting.md", "references/craft/color-and-grade.md"]),
    ("05-craft-sound-edit-continuity.md", "Craft: sound, editing rhythm, continuity",
     ["references/craft/sound-design.md", "references/craft/editing-rhythm.md", "references/craft/continuity.md"]),
    ("06-image-and-video-prompt-formats.md", "Translation: image prompt and video block formats",
     ["references/translation/image-prompts.md", "references/translation/video-prompts.md"]),
    ("07-models-seedance-nano-banana.md", "Models: Seedance 2.5 and Nano Banana Pro",
     ["references/models/seedance-2.5.md", "references/models/nano-banana-pro.md"]),
    ("08-style-dna-library.md", "Style DNA library", ["references/style-dna-library.md"]),
    ("09-troubleshooting.md", "Troubleshooting", ["references/troubleshooting.md"]),
]

HEADER = """<!-- Generated by build/build_portable.py from skills/ai-filmmaker/. Do not edit by hand. -->
# {title}

Part of the AI Filmmaker knowledge set (files 00-09). When a section mentions a path such as
`references/craft/lighting.md`, search the knowledge files for "Source: references/craft/lighting.md".
"""


def strip_frontmatter(text):
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            return text[end + 5:].lstrip("\n")
    return text


def source_section(rel):
    text = strip_frontmatter((SKILL / rel).read_text(encoding="utf-8")).rstrip() + "\n"
    return "\n---\n\n<!-- Source: {0} -->\n**Source: {0}**\n\n{1}".format(rel, text)


def build():
    files = {}
    covered = set()
    for name, title, sources in GROUPS:
        body = HEADER.format(title=title) + "".join(source_section(s) for s in sources)
        files[KNOWLEDGE / name] = body
        covered.update(sources)

    # every reference file must be covered exactly once
    all_refs = {str(p.relative_to(SKILL)) for p in REF.rglob("*.md")} | {"SKILL.md"}
    missing = sorted(all_refs - covered)
    if missing:
        raise SystemExit("not covered by any knowledge file: " + ", ".join(missing))

    system = SYSTEM_PROMPT.read_text(encoding="utf-8")
    full = ["<!-- Generated by build/build_portable.py. Paste this whole file into any LLM with a large context window. -->\n",
            system.rstrip() + "\n"]
    for path in files:
        full.append("\n\n" + "=" * 78 + "\n" + re.sub(r"^<!--.*?-->\n", "", files[path]))
    files[OUT / "ai-filmmaker-full.md"] = "".join(full)
    return files, system


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args(argv)

    files, system = build()
    problems = []
    if len(system) > SYSTEM_PROMPT_LIMIT:
        problems.append("SYSTEM_PROMPT.md is %d characters (limit %d)" % (len(system), SYSTEM_PROMPT_LIMIT))
    if len(GROUPS) > 10:
        problems.append("more than 10 knowledge files")

    if args.check:
        for path, content in files.items():
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                problems.append("stale: %s (run python3 build/build_portable.py)" % path.relative_to(ROOT))
        extra = {p for p in KNOWLEDGE.glob("*.md")} - set(files)
        problems += ["unexpected file: %s" % p.relative_to(ROOT) for p in sorted(extra)]
    else:
        KNOWLEDGE.mkdir(parents=True, exist_ok=True)
        for old in KNOWLEDGE.glob("*.md"):
            if old not in files:
                old.unlink()
        for path, content in files.items():
            path.write_text(content, encoding="utf-8")
        print("wrote %d knowledge files + ai-filmmaker-full.md; SYSTEM_PROMPT.md is %d chars"
              % (len(GROUPS), len(system)))

    for p in problems:
        print("ERROR: " + p, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
